import 'package:flutter/material.dart';
import 'package:flx_nocode_flutter/features/entity/models/action.dart';
import 'package:flx_nocode_flutter/features/field/domain/field_value_label_resolver.dart';
import 'package:hive_ce/hive.dart';

/// Represents a single field definition in a dynamic entity configuration.
///
/// This model describes how a field should be rendered, validated, and
/// whether it can be created/updated/copied inside UI or forms.
class EntityField extends HiveObject {
  /// Human-readable label to display in UI.
  final String label;

  /// Unique reference/key for the field.
  final String reference;

  /// Field type string.
  ///
  /// Supported patterns (see `EntityFieldDomainX` helpers):
  /// - `text`, `select`, `bool`, `permission`
  /// - `number` or `number(<decimal>)` → use `decimal` getter
  /// - `date` or `datetime(<format>)` → use `isDateTime`/`dateTimeFormat`
  final String type;

  /// Optional width of the column when rendered in tables/grids.
  final double? columnWidth;

  /// Whether the field value is automatically generated.
  final bool? autoGenerated;

  /// Whether the field value is required.
  final bool required;

  /// Regex pattern for validating the field.
  final String? pattern;

  /// Error message shown if [pattern] does not match.
  final String? patternError;

  /// Source identifier for option-based fields.
  final String? optionsSource;

  /// Minimum text length for this field.
  final int? minLength;

  /// Maximum text length for this field.
  final int? maxLength;

  /// Whether this field is allowed to be set on create.
  final bool? allowCreate;

  /// Whether this field can be updated after creation.
  final bool? allowUpdate;

  /// Whether the field value can be copied from UI.
  final bool? isCopyable;

  /// Whether hovering over the cell shows a tooltip with extra information.
  ///
  /// When `true`, the rendered cell is wrapped in a `Tooltip` whose message is
  /// the field's [label]. When `false` or `null`, the cell renders normally.
  final bool? isTooltip;

  /// Whether to render this field as a chip.
  final bool? isChip;

  /// Custom color overrides for chips based on raw values.
  final Map<String, String>? chipColors;

  /// Maps raw system/database codes (e.g. `EVALUATION_APPROVAL`) to human-readable
  /// display labels (e.g. `Evaluasi & Persetujuan`).
  ///
  /// Accepted JSON keys: `value_labels` (recommended), `valueLabels`, or
  /// `chip_labels` / `chipLabels` (backward-compatible alias).
  /// Applies to both chip and non-chip fields across table, detail, filter,
  /// export, and print.
  final Map<String, String>? valueLabels;

  /// Additional options for dropdown/lookup type fields.
  final FieldOptions? options;

  /// Custom background colors based on values.
  final Map<String, String>? backgroundColors;

  /// Custom text colors based on values.
  final Map<String, String>? textColors;

  /// Whether this column is pinned on the table.
  final bool? isPinned;

  /// Whether this field should be rendered as a context badge at the top of entity views.
  final bool? isBadge;

  /// Optional icon name for the badge or field (e.g. 'calendar', 'location', 'person', 'category').
  final String? iconName;

  /// Optional action triggered when clicking this field/cell.
  final ActionD? action;

  /// Creates a new [EntityField] configuration.
  EntityField({
    required this.label,
    required this.reference,
    required this.type,
    this.columnWidth,
    this.autoGenerated,
    this.required = false,
    this.pattern,
    this.patternError,
    this.optionsSource,
    this.minLength,
    this.maxLength,
    this.allowCreate,
    this.allowUpdate,
    this.isCopyable,
    this.isTooltip,
    this.isChip,
    this.chipColors,
    this.valueLabels,
    this.options,
    this.backgroundColors,
    this.textColors,
    this.isPinned,
    this.isBadge,
    this.iconName,
    this.action,
  });

  /// Creates an [EntityField] instance from JSON.
  ///
  /// Expected JSON structure:
  /// ```json
  /// {
  ///   "label": "Name",
  ///   "reference": "name",
  ///   "type": "text",
  ///   "column_width": 150,
  ///   "auto_generated": false,
  ///   "required": true,
  ///   "is_copyable": true
  /// }
  /// ```
  factory EntityField.fromJson(Map<String, dynamic> json) {
    return EntityField(
      optionsSource: json['options_source'] as String?,
      columnWidth: (json['column_width'] as num?)?.toDouble(),
      label: json['label'] as String? ?? '',
      reference: json['reference'] as String? ?? '',
      type: json['type'] as String? ?? '',
      autoGenerated: json['auto_generated'] as bool?,
      required: json['required'] as bool? ?? false,
      pattern: json['pattern'] as String?,
      patternError: json['pattern_error'] as String?,
      minLength: json['min_length'] as int?,
      maxLength: json['max_length'] as int?,
      allowCreate: json['allow_create'] as bool?,
      allowUpdate: json['allow_update'] as bool?,
      isCopyable: json['is_copyable'] as bool?,
      isTooltip: json['is_tooltip'] as bool?,
      isChip: json['is_chip'] as bool?,
      chipColors: FieldValueLabelResolver.parseStringMap(
        json['chip_colors'] ?? json['chipColors'],
      ),
      valueLabels: FieldValueLabelResolver.parseStringMap(
        json['value_labels'] ??
            json['valueLabels'] ??
            json['chip_labels'] ??
            json['chipLabels'],
      ),
      backgroundColors: json['background_colors'] is Map
          ? (json['background_colors'] as Map).cast<String, String>()
          : (json['background_colors'] is String
              ? {'*': json['background_colors'] as String}
              : null),
      textColors: json['text_colors'] is Map
          ? (json['text_colors'] as Map).cast<String, String>()
          : (json['text_colors'] is String
              ? {'*': json['text_colors'] as String}
              : null),
      isPinned: json['is_pinned'] == true || json['pinned'] == true,
      isBadge: json['is_badge'] == true || json['badge'] == true,
      iconName: (json['icon'] ?? json['badge_icon'] ?? json['icon_name']) as String?,
      action: json['action'] is Map
          ? ActionD.fromJson(Map<String, dynamic>.from(json['action'] as Map))
          : (json['click_action'] is Map
              ? ActionD.fromJson(
                  Map<String, dynamic>.from(json['click_action'] as Map))
              : null),
    );
  }

  /// Creates an empty/default field.
  factory EntityField.empty() => EntityField(
        label: '',
        reference: '',
        type: '',
      );

  /// Returns a copy of this field with overridden values.
  EntityField copyWith({
    String? label,
    String? reference,
    String? type,
    double? columnWidth,
    bool? autoGenerated,
    bool? required,
    String? pattern,
    String? patternError,
    String? optionsSource,
    int? minLength,
    int? maxLength,
    bool? allowCreate,
    bool? allowUpdate,
    bool? isCopyable,
    bool? isTooltip,
    bool? isChip,
    Map<String, String>? chipColors,
    Map<String, String>? valueLabels,
    FieldOptions? options,
    Map<String, String>? backgroundColors,
    Map<String, String>? textColors,
    bool? isPinned,
    bool? isBadge,
    String? iconName,
    ActionD? action,
  }) {
    return EntityField(
      label: label ?? this.label,
      reference: reference ?? this.reference,
      type: type ?? this.type,
      columnWidth: columnWidth ?? this.columnWidth,
      autoGenerated: autoGenerated ?? this.autoGenerated,
      required: required ?? this.required,
      pattern: pattern ?? this.pattern,
      patternError: patternError ?? this.patternError,
      optionsSource: optionsSource ?? this.optionsSource,
      minLength: minLength ?? this.minLength,
      maxLength: maxLength ?? this.maxLength,
      allowCreate: allowCreate ?? this.allowCreate,
      allowUpdate: allowUpdate ?? this.allowUpdate,
      isCopyable: isCopyable ?? this.isCopyable,
      isTooltip: isTooltip ?? this.isTooltip,
      isChip: isChip ?? this.isChip,
      chipColors: chipColors ?? this.chipColors,
      valueLabels: valueLabels ?? this.valueLabels,
      options: options ?? this.options,
      backgroundColors: backgroundColors ?? this.backgroundColors,
      textColors: textColors ?? this.textColors,
      isPinned: isPinned ?? this.isPinned,
      isBadge: isBadge ?? this.isBadge,
      iconName: iconName ?? this.iconName,
      action: action ?? this.action,
    );
  }

  /// Effective mapping of raw code -> human-readable display label,
  /// combining static `options_source` (`values(...)`) with explicit `valueLabels`.
  Map<String, String> get effectiveValueLabels =>
      FieldValueLabelResolver.effectiveLabels(
        valueLabels: valueLabels,
        optionsSource: optionsSource,
      );

  /// Whether this field defines any static code -> label mappings
  /// (either via `value_labels`/`chip_labels` or static `options_source`).
  bool get hasValueLabels => effectiveValueLabels.isNotEmpty;

  /// Resolves [rawValue] to its display label using this field's configuration.
  String resolveDisplayLabel(dynamic rawValue) =>
      FieldValueLabelResolver.resolveLabel(
        rawValue,
        valueLabels: valueLabels,
        optionsSource: optionsSource,
      );

  /// Converts this field definition into JSON map.
  Map<String, dynamic> toJson() {
    return {
      if (action != null) 'action': action!.toJson(),
      'options_source': optionsSource,
      'column_width': columnWidth,
      'label': label,
      'reference': reference,
      'type': type,
      'auto_generated': autoGenerated,
      'required': required,
      'pattern': pattern,
      'pattern_error': patternError,
      'min_length': minLength,
      'max_length': maxLength,
      'allow_create': allowCreate,
      'allow_update': allowUpdate,
      'is_copyable': isCopyable,
      'is_tooltip': isTooltip,
      'is_chip': isChip,
      'chip_colors': chipColors,
      if (valueLabels != null) 'value_labels': valueLabels,
      if (isPinned != null) 'is_pinned': isPinned,
      if (isBadge != null) 'is_badge': isBadge,
      if (iconName != null) 'icon': iconName,
      'background_colors': (backgroundColors?.length == 1 && backgroundColors!.containsKey('*'))
          ? backgroundColors!['*']
          : backgroundColors,
      'text_colors': (textColors?.length == 1 && textColors!.containsKey('*'))
          ? textColors!['*']
          : textColors,
    };
  }
}

/// Options configuration for dropdown/lookup fields.
class FieldOptions extends HiveObject {
  /// Source of data (API endpoint, Hive box, etc).
  final String source;

  /// Field to show as label when rendering options.
  final String labelField;

  /// Field used as value in selection.
  final String valueField;

  FieldOptions({
    required this.source,
    required this.labelField,
    required this.valueField,
  });

  /// Creates a [FieldOptions] instance from JSON.
  factory FieldOptions.fromJson(Map<String, dynamic> json) {
    return FieldOptions(
      source: json['source'] as String? ?? '',
      labelField: json['label_field'] as String? ?? '',
      valueField: json['value_field'] as String? ?? '',
    );
  }

  /// Converts this options configuration into JSON map.
  Map<String, dynamic> toJson() {
    return {
      'source': source,
      'label_field': labelField,
      'value_field': valueField,
    };
  }
}

extension EntityFieldIconX on EntityField {
  IconData get icon {
    if (type.contains('number')) return Icons.tag;
    if (type == 'bool') return Icons.toggle_on;
    if (type.contains('datetime') || type == 'date') return Icons.date_range;
    if (type == 'select') return Icons.arrow_drop_down_circle;
    if (type == 'permission') return Icons.security;
    return Icons.text_fields;
  }
}
